// Build-time only: evaluate the repository's authored data in an isolated context.
// The Worker imports static output and never evaluates code or loads browser globals.
import fs from "node:fs";
import vm from "node:vm";
import crypto from "node:crypto";
const root = new URL("../", import.meta.url);
// Git may check text files out as CRLF on Windows. Hash and compare the same
// canonical text on every platform; substantive source changes still fail.
const normalize = (text) => text.replace(/\r\n/g, "\n");
const read = (p) => normalize(fs.readFileSync(new URL("../" + p, root), "utf8"));
const sources = [
  "site/data/content.js",
  "site/js/story.js",
  "site/js/state.js",
  "site/js/story-map.js",
  "site/js/story-ui.js",
  "site/js/items.js",
  "site/js/pages/map.js",
  "site/js/pages/d4.js",
  "site/js/pages/church.js",
  "site/js/pages/journal.js",
  "site/js/pages/ending.js",
  "site/js/full-assimilation.js",
];
const context = { window: {} };
vm.runInNewContext(read(sources[0]), context, { timeout: 1000 });
const header = "// Generated by scripts/sync-content.mjs; do not edit.\n";
const story = read("site/js/story.js");
const ui = read("site/js/story-ui.js");
const recap = ui.slice(
  ui.indexOf("  function recapText("),
  ui.indexOf("  function review()"),
);
const files = {
  "src/game/content.ts":
    header +
    "export const CONTENT = " +
    JSON.stringify(context.window.CONTENT, null, 2) +
    ";\n",
  "src/game/story.ts":
    header +
    "// @ts-nocheck\nexport function createStory(S, CONTENT, random) {\nconst window = {CC:{state:S}, CONTENT}; const Math = Object.create(globalThis.Math); Math.random = random;\n" +
    story +
    "\nreturn window.CC.story;\n}\nexport function recapText(r, CONTENT) { const V=CONTENT.v02, window={CONTENT};\n" +
    recap +
    "\nreturn recapText(r);\n}\n",
  "src/game/source-manifest.json":
    JSON.stringify(
      Object.fromEntries(
        sources.map((p) => [
          p,
          crypto.createHash("sha256").update(read(p)).digest("hex"),
        ]),
      ),
      null,
      2,
    ) + "\n",
};
for (const [p, content] of Object.entries(files)) {
  const path = new URL(p, root);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(path) || normalize(fs.readFileSync(path, "utf8")) !== content)
      throw Error(
        "Upstream changed; audit the adapter before running sync-content: " + p,
      );
  } else fs.writeFileSync(path, content);
}
